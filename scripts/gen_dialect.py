import json, struct, sys
from pymavlink.dialects.v20 import ardupilotmega as m
from pymavlink import mavutil
msgs = []
for mid, c in sorted(m.mavlink_map.items()):
    types = dict(zip(c.fieldnames, c.fieldtypes))
    arr = dict(zip(c.ordered_fieldnames, c.array_lengths))
    fields = []
    for f in c.ordered_fieldnames:
        t = types[f].replace('_t','')
        fields.append([f, t, arr[f]])
    size = struct.calcsize(c.unpacker.format)
    msgs.append([mid, c.msgname, c.crc_extra, size, fields])
def enum(name):
    return {int(k): v.name for k, v in m.enums[name].items() if not v.name.endswith('_ENUM_END')}
out = {
 'messages': msgs,
 'enums': {n: enum(n) for n in ['MAV_TYPE','MAV_AUTOPILOT','MAV_STATE','MAV_SEVERITY','MAV_RESULT']},
 'copterModes': {int(k):v for k,v in mavutil.mode_mapping_acm.items()},
}
ts = "// GENERATED by scripts/gen_dialect.py from pymavlink (ardupilotmega dialect, MAVLink 2).\n// Do not edit by hand: CRC_EXTRA values must match the dialect exactly.\n\n"
ts += "export type FieldType = 'int8' | 'uint8' | 'int16' | 'uint16' | 'int32' | 'uint32' | 'int64' | 'uint64' | 'float' | 'double' | 'char';\n"
ts += "/** [msgId, name, crcExtra, fullPayloadLength, fields in wire order: [name, type, arrayLength]] */\n"
ts += "export type MessageDef = [number, string, number, number, [string, FieldType, number][]];\n\n"
ts += "export const MESSAGES: MessageDef[] = " + json.dumps(msgs, separators=(',',':')) + ";\n\n"
ts += "export const ENUMS: Record<string, Record<number, string>> = " + json.dumps(out['enums'], separators=(',',':')) + ";\n\n"
ts += "/** ArduCopter custom_mode -> mode name */\nexport const COPTER_MODES: Record<number, string> = " + json.dumps(out['copterModes']) + ";\n"
open(sys.argv[1],'w').write(ts)
print(len(msgs), set(f[1] for msg in msgs for f in msg[4]))
